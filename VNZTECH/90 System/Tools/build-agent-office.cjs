/* Bundle the two fixed local sources; no dependencies or runtime file loading. */
const fs = require('node:fs');
const path = require('node:path');
const { Script } = require('node:vm');
const directory = path.resolve(__dirname, '../../.obsidian/plugins/vnz-agent-office');
const roster = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../Company Roster.json'), 'utf8'));
if (roster.agents.length !== 20 || new Set(roster.agents.map(agent => agent.name)).size !== 20) throw new Error('Expected 20 unique company agents');
const scene = fs.readFileSync(path.join(directory, 'office-scene.js'), 'utf8');
const entry = fs.readFileSync(path.join(directory, 'office-view.js'), 'utf8');
const bundle = `/* VNZ Agent Office. Generated by 90 System/Tools/build-agent-office.cjs. */\n'use strict';\nconst COMPANY_ROSTER = ${JSON.stringify(roster)};\nconst { renderOffice, AGENT_LAYOUT } = (() => {\nconst module = { exports: {} };\n${scene}\nreturn module.exports;\n})();\n${entry}`;
new Script(bundle, { filename: 'main.js' });
fs.writeFileSync(path.join(directory, 'main.js'), bundle);
console.log('Built VNZ Agent Office main.js');
